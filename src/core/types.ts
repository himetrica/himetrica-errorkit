// ErrorKit wire format and the shapes the grouping core works on.
//
// One format for every platform. The SDK sends a batch of items: a full `event`
// the first time a fingerprint shows up in a session, and a `count` afterwards.
// The server only ever processes an event whose fingerprint it has not seen for
// that release; everything else is a counter. That is what keeps storage
// proportional to distinct errors instead of volume.

export type Level = "fatal" | "error" | "warning" | "info";

export type Mechanism =
  | "onerror"
  | "unhandledrejection"
  | "console"
  | "boundary"
  | "wrapped" // setTimeout / addEventListener / rAF wrappers
  | "request" // server: request handler (Next onRequestError, framework middleware)
  | "uncaught" // server: process uncaughtException
  | "manual"
  | "legacy"; // converted from the v1 /er payload

export interface Frame {
  /** Path as reported by the runtime, query and hash already stripped. */
  file: string;
  function?: string;
  line?: number;
  column?: number;
  inApp: boolean;
  /** Set by server symbolication: the minified frame this one was mapped from. */
  raw?: { file: string; function?: string; line?: number; column?: number };
  /** Set by server symbolication when the map carries sources: lines around `line`. */
  context?: { pre: string[]; line: string; post: string[] };
}

export interface ExceptionValue {
  /** `TypeError`, `ChunkLoadError`... `Error` when the runtime gives nothing better. */
  type: string;
  message: string;
  /** Innermost call last, the order V8 prints is reversed so index 0 is the throw site. */
  frames: Frame[];
}

export interface ErrorEvent {
  /** UUID generated by the SDK; retries with the same id are dropped server side. */
  eventId: string;
  /** Epoch ms of the occurrence, not of the delivery. */
  timestamp: number;
  platform: "browser" | "node";
  sdk: { name: string; version: string };
  level: Level;
  mechanism: Mechanism;
  handled: boolean;
  release?: string;
  environment?: string;
  /** Outermost first, then each `cause`, at most 5. */
  exceptions: ExceptionValue[];
  fingerprint: string;
  groupingVersion: number;
  /** User override passed to captureException; `{{default}}` extends the computed one. */
  customFingerprint?: string[];
  visitorId?: string;
  sessionId?: string;
  userId?: string;
  url?: string;
  tags?: Record<string, string>;
  extra?: Record<string, unknown>;
  /** Which source map belongs to which bundle file (injected Debug IDs). */
  debugMeta?: { images: DebugImage[] };
}

/** One bundle file and the Debug ID the build stamped into it and its .map. */
export interface DebugImage {
  type: "sourcemap";
  /** URL or path of the bundle as it appears in stack frames. */
  codeFile: string;
  debugId: string;
}

/** Repeats of an already-sent fingerprint, folded by the SDK until the next flush. */
export interface ErrorCount {
  fingerprint: string;
  groupingVersion: number;
  count: number;
  firstTimestamp: number;
  lastTimestamp: number;
  release?: string;
  environment?: string;
  visitorId?: string;
  sessionId?: string;
}

export interface ErrorBatch {
  events: ErrorEvent[];
  counts: ErrorCount[];
}
